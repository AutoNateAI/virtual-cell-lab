#!/usr/bin/env python3
"""Run x03: open a real Perturb-seq file and look at what is actually in it.

Reads the pilot experiment from Adamson et al. 2016, as harmonized by scPerturb, and asks simple questions of the matrix: how
big is it, how much of it is zero, and did the genes that were targeted actually go down? No model is involved.

    pip install h5py numpy scipy
    python3 -I runs/x03-open-a-dataset/open.py path/to/AdamsonWeissman2016_GSM2406675_10X001.h5ad

The file is at https://zenodo.org/records/13350497 (CC BY 4.0).
"""
import hashlib
import json
import sys
from pathlib import Path

import h5py
import numpy as np
from scipy import sparse

HERE = Path(__file__).resolve().parent


def decode(values):
    return np.array([v.decode() if isinstance(v, bytes) else str(v) for v in values])


def categorical(group):
    """A code of -1 means the cell has no label. Indexing with it would silently return the last category."""
    names = decode(group["categories"][()])
    codes = group["codes"][()]
    out = names[np.maximum(codes, 0)].astype(object)
    out[codes < 0] = ""
    return out.astype(str)


def main(path):
    digest = hashlib.sha256(Path(path).read_bytes()).hexdigest()
    with h5py.File(path, "r") as f:
        x = f["X"]
        shape = tuple(int(n) for n in x.attrs["shape"])
        matrix = sparse.csc_matrix((x["data"][()], x["indices"][()], x["indptr"][()]), shape=shape).tocsr()
        perturbation = categorical(f["obs"]["perturbation"])
        var = f["var"]
        index_key = var.attrs["_index"]
        symbols = decode(var[index_key][()])
    cells, genes = matrix.shape
    nonzero = int((matrix > 0).sum())
    detected = np.asarray((matrix > 0).sum(axis=1)).ravel()
    counts = np.asarray(matrix.sum(axis=1)).ravel()
    per10k = sparse.diags(1e4 / np.maximum(counts, 1)) @ matrix
    labels, sizes = np.unique(perturbation[perturbation != ""], return_counts=True)
    out = {
        "file_sha256": digest, "cells": cells, "genes": genes, "entries": cells * genes, "nonzero_entries": nonzero,
        "percent_zero": round(100 * (1 - nonzero / (cells * genes)), 2),
        "integer_counts": bool(np.all(matrix.data == np.round(matrix.data))),
        "median_genes_detected_per_cell": float(np.median(detected)), "median_share_of_genes_detected_percent": round(float(100 * np.median(detected) / genes), 2),
        "median_molecules_per_cell": float(np.median(counts)), "cells_without_a_label": int((perturbation == "").sum()), "labels": {str(a): int(b) for a, b in zip(labels, sizes)}, "targets": {},
    }
    for label in labels:
        target = str(label).split("_")[0]
        if target in {"*", "62(mod)"} or target not in symbols:
            continue
        gene = np.where(symbols == target)[0][0]
        inside = perturbation == label
        outside = ~inside & (perturbation != "*") & (perturbation != "")
        col = per10k[:, gene].toarray().ravel()
        raw = matrix[:, gene].toarray().ravel()
        a, b = float(col[inside].mean()), float(col[outside].mean())
        out["targets"][target] = {
            "guide": str(label), "cells": int(inside.sum()), "mean_per_10k_in_targeted_cells": round(a, 3), "mean_per_10k_in_other_cells": round(b, 3),
            "ratio_targeted_to_other": round(a / b, 3) if b else None,
            "percent_detected_in_targeted_cells": round(float(100 * (raw[inside] > 0).mean()), 1), "percent_detected_in_other_cells": round(float(100 * (raw[outside] > 0).mean()), 1),
        }
    (HERE / "results.json").write_text(json.dumps(out, indent=2) + "\n")
    (HERE / "results.md").write_text(report(out))
    print(report(out))


def report(o):
    lines = ["# Run x03: opening a real Perturb-seq file", "", "Generated by `open.py` from the Adamson et al. 2016 pilot, as harmonized by scPerturb.", "",
             f"- Matrix: {o['cells']:,} cells by {o['genes']:,} genes, {o['entries']:,} entries", f"- Zero entries: {o['percent_zero']}%", f"- Median genes detected per cell: {o['median_genes_detected_per_cell']:,.0f} ({o['median_share_of_genes_detected_percent']}%)", f"- Median molecules per cell: {o['median_molecules_per_cell']:,.0f}", f"- Cells without a label: {o['cells_without_a_label']}; ambiguous label (*): {o['labels'].get('*', 0)}", "",
             "## Did the targeted gene go down?", "", "| Target | Cells | Mean per 10k, targeted cells | Mean per 10k, other cells | Ratio | Detected, targeted | Detected, other |", "|---|---|---|---|---|---|---|"]
    for t, r in sorted(o["targets"].items()):
        lines.append(f"| {t} | {r['cells']} | {r['mean_per_10k_in_targeted_cells']} | {r['mean_per_10k_in_other_cells']} | {r['ratio_targeted_to_other']} | {r['percent_detected_in_targeted_cells']}% | {r['percent_detected_in_other_cells']}% |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main(sys.argv[1])
